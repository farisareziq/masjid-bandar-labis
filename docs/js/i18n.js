var I18N = {
  currentLang: "ms",

  getLang: function () {
    try {
      var saved = localStorage.getItem("mbj-lang");
      if (saved === "en" || saved === "ms") return saved;
    } catch (e) {}
    return "ms";
  },

  t: function (key) {
    var table = I18N_DATA[this.currentLang] || I18N_DATA.ms;
    return table[key] !== undefined ? table[key] : (I18N_DATA.ms[key] || key);
  },

  apply: function (lang) {
    this.currentLang = lang;
    try { localStorage.setItem("mbj-lang", lang); } catch (e) {}

    document.documentElement.lang = lang === "ms" ? "ms" : "en";

    // Teks biasa
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      var val = I18N.t(key);
      if (val !== key) el.textContent = val;
    });

    // Teks dengan HTML dalaman (span dsb.)
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-html");
      var val = I18N.t(key);
      if (val !== key) el.innerHTML = val;
    });

    // Atribut (cth: title:key, alt:key, placeholder:key)
    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      el.getAttribute("data-i18n-attr").split(",").forEach(function (pair) {
        var parts = pair.split(":");
        if (parts.length === 2) {
          var attr = parts[0];
          var val = I18N.t(parts[1]);
          if (val !== parts[1]) el.setAttribute(attr, val);
        }
      });
    });

    // Butang tukar bahasa
    var toggle = document.getElementById("langToggle");
    if (toggle) {
      toggle.textContent = lang === "ms" ? "EN" : "BM";
      toggle.setAttribute("aria-label", I18N.t("lang.aria"));
    }

    // Beritahu skrip lain (widget solat dsb.)
    document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
  },

  init: function () {
    var self = this;
    this.apply(this.getLang());

    var toggle = document.getElementById("langToggle");
    if (toggle) {
      toggle.addEventListener("click", function () {
        var next = self.currentLang === "ms" ? "en" : "ms";
        self.apply(next);
      });
    }
  },
};

document.addEventListener("DOMContentLoaded", function () {
  I18N.init();
});
